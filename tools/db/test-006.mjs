import { loadPGlite } from './pglite.mjs';
const PGlite = await loadPGlite();
import { readdirSync, readFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
const dir = fileURLToPath(new URL('../../supabase/migrations/', import.meta.url));
const B = 'b0000000-0000-4000-8000-00000000000b', S = 'c0000000-0000-4000-8000-00000000000c';
let fails = 0;
const ok = (c, m) => { console.log((c ? 'OK   ' : 'FOUT ') + m); if (!c) fails++; };
const db = new PGlite();
await db.exec(`
create schema auth; create table auth.users (id uuid primary key, email text);
create function auth.uid() returns uuid language sql stable as $$ select nullif(current_setting('request.jwt.claims', true)::jsonb ->> 'sub', '')::uuid $$;
create role anon nologin; create role authenticated nologin;
grant usage on schema public to anon, authenticated; grant usage on schema auth to anon, authenticated;
grant execute on function auth.uid() to anon, authenticated;
create publication supabase_realtime;
insert into auth.users values ('${B}','b@test.nl'),('${S}','s@test.nl');`);
for (const f of readdirSync(dir).filter(f => f.endsWith('.sql') && f < '006').sort()) await db.exec(readFileSync(dir + f, 'utf8'));
await db.exec(`insert into lists_tasks (user_id, name, link) values ('${B}','Was',null),('${B}','Winkelen','list'),('${S}','Haar taak',null);`);
await db.exec(readFileSync(dir + '006_taken_later.sql', 'utf8'));
ok(true, '006 loopt zonder fout op bestaande taken');
const as = (uid, sql) => db.transaction(async tx => {
  await tx.query(`select set_config('request.jwt.claims', $1, true)`, [JSON.stringify({ sub: uid, role: 'authenticated' })]);
  await tx.exec('set local role authenticated');
  return (await tx.query(sql)).rows;
});
const err = async (uid, sql) => { try { await as(uid, sql); return ''; } catch (e) { return e.message; } };
ok((await db.query('select count(*)::int n from lists_tasks where later')).rows[0].n === 0, 'bestaande taken staan bij Vandaag');
ok((await db.query('select count(*)::int n from lists_tasks')).rows[0].n === 3, 'geen taken verloren');
await as(B, `update lists_tasks set later = true where name = 'Was'`);
ok((await as(B, `select later from lists_tasks where name='Was'`))[0].later === true, 'naar Later zetten werkt');
