ok(/check/.test(await err(B, `update lists_tasks set link = 'buy' where name = 'Was'`)), 'taak bij Later kan niet gekoppeld worden zonder naar Vandaag');
ok(!(await err(B, `update lists_tasks set link = 'buy', later = false where name = 'Was'`)), 'koppelen + naar Vandaag tegelijk mag');
await as(B, `insert into lists_tasks (name, later) values ('Zolder', true)`);
ok((await as(B, `select name from lists_tasks order by name`)).map(r => r.name).join() === 'Was,Winkelen,Zolder', 'Bjorn ziet alleen zijn taken');
ok((await as(S, `select name from lists_tasks`)).map(r => r.name).join() === 'Haar taak', 'S ziet alleen haar taken (Thuis blijft privé)');
ok((await as(B, `insert into lists_tasks (id, name, later) values ('e0000000-0000-4000-8000-00000000000e','Upsert',true) on conflict (id) do update set later = excluded.later returning later`))[0].later === true, 'upsert zoals de app');
